#!/usr/bin/env python3
"""Fail CI if a PR introduces new `//` inline comments in code.

Soft fences in AGENTS.md are easy for agents to ignore; this gate turns the
"no inline // comments" rule into a hard fence. Existing lines are untouched.
"""
import os
import re
import subprocess
import sys

BASE_REF = os.environ.get("BASE_REF") or os.environ.get("GITHUB_BASE_REF", "")
CODE_EXT = {".java", ".kt", ".kts", ".cpp", ".cc", ".c", ".h", ".hpp", ".py", ".sh"}
BANNED_MARKERS = ("co-authored-by:", "generated by", "ai-assisted", "ai generated")


def run(*args):
    return subprocess.run(args, capture_output=True, text=True, check=True)


def base_commit():
    if BASE_REF:
        name = BASE_REF if BASE_REF.startswith("origin/") else "origin/" + BASE_REF
        try:
            run("git", "rev-parse", "--verify", name)
            return name
        except subprocess.CalledProcessError:
            try:
                run("git", "rev-parse", "--verify", BASE_REF)
                return BASE_REF
            except subprocess.CalledProcessError:
                pass
    try:
        run("git", "rev-parse", "--verify", "HEAD~1")
        return "HEAD~1"
    except subprocess.CalledProcessError:
        return None


def collect(diff_range):
    cmd = ["git", "diff", "--unified=0", diff_range, "--"]
    for ext in CODE_EXT:
        cmd.append(f"*{ext}")
    out = run(*cmd).stdout

    findings = []
    current_file = None
    new_line_no = 0
    in_hunk = False
    for raw in out.splitlines():
        if raw.startswith("+++ "):
            p = raw[4:].split("\t", 1)[0]
            p = p[2:] if p.startswith("b/") else p
            current_file = p
            in_hunk = False
            continue
        m = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@", raw)
        if m:
            new_line_no = int(m.group(1))
            in_hunk = True
            continue
        if not in_hunk:
            continue
        if raw.startswith("+"):
            text = raw[1:]
            if text.strip().startswith("//"):
                findings.append((current_file or "?", new_line_no, text.rstrip()))
            new_line_no += 1
        elif raw.startswith("-"):
            pass
        else:
            # context line consumes a new-file line
            if raw.startswith(" "):
                new_line_no += 1
    return findings


def check_messages(diff_range):
    base = diff_range.split("...")[0]
    cmd = ["git", "log", "--format=%B%x1e", f"{base}..HEAD"]
    try:
        out = run(*cmd).stdout.lower()
    except subprocess.CalledProcessError:
        out = run("git", "log", "-1", "--format=%B").stdout.lower()
    bad = [m for m in BANNED_MARKERS if m in out]
    return bad


def main():
    base = base_commit()
    if base is None:
        print("No base commit to compare; skipping.")
        return 0
    diff_range = f"{base}...HEAD"

    findings = collect(diff_range)
    bad_markers = check_messages(diff_range)

    if findings:
        print("FAIL: new inline `//` comments introduced:")
        for f, ln, text in findings:
            print(f"  {f}:{ln}: {text}")
    if bad_markers:
        print("FAIL: AI authorship marker found in commit message(s): " + ", ".join(bad_markers))

    if findings or bad_markers:
        return 1
    print("OK: no new inline `//` comments or AI authorship markers.")
    return 0


if __name__ == "__main__":
    sys.exit(main())